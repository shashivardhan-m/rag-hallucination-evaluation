"""Pydantic v2 schemas for all API request and response data transfers."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


# ---------------------------------------------------------
# Document & Chunk Schemas
# ---------------------------------------------------------

class DocumentInfo(BaseModel):
    """Document entity view."""
    id: str
    filename: str
    file_type: str
    file_size: int
    num_chunks: int
    upload_time: datetime
    description: Optional[str] = None
    metadata_json: Optional[str] = "{}"

    model_config = ConfigDict(from_attributes=True)


class DocumentUploadResponse(BaseModel):
    """Response returned upon successful document upload and chunk indexing."""
    id: str
    filename: str
    file_type: str
    file_size: int
    num_chunks: int
    upload_time: datetime
    message: str = "Document processed and indexed successfully"

    model_config = ConfigDict(from_attributes=True)


class DocumentListResponse(BaseModel):
    """List of uploaded documents."""
    total: int
    documents: List[DocumentInfo]


class ChunkInfo(BaseModel):
    """Information regarding a single indexed document chunk."""
    id: str
    document_id: str
    chunk_index: int
    content: str
    char_count: int
    token_estimate: int
    embedding_model: str

    model_config = ConfigDict(from_attributes=True)


class ChunkListResponse(BaseModel):
    """Paginated list of document chunks."""
    total: int
    chunks: List[ChunkInfo]


# ---------------------------------------------------------
# Retrieval Schemas
# ---------------------------------------------------------

class RetrievedChunk(BaseModel):
    """Details of a retrieved chunk matching a query."""
    chunk_id: str
    document_id: str
    filename: str
    chunk_index: int
    content: str
    score: float
    rank: int


class RetrievalQuery(BaseModel):
    """Payload to perform similarity or hybrid search."""
    query: str
    top_k: int = Field(default=5, ge=1, le=50)
    mode: str = Field(default="semantic", description="Retrieval mode: 'semantic' or 'hybrid'")
    use_reranking: bool = False
    document_id: Optional[str] = None


class RetrievalResult(BaseModel):
    """Result of vector retrieval."""
    query: str
    total_retrieved: int
    retrieval_mode: str
    reranked: bool
    latency_ms: float
    chunks: List[RetrievedChunk]


# ---------------------------------------------------------
# QA & LLM Inference Schemas
# ---------------------------------------------------------

class AnswerResult(BaseModel):
    """Answer generated by LLM along with runtime stats."""
    answer: str
    latency_ms: float
    model: str
    backend: str
    retrieved_chunks: Optional[List[RetrievedChunk]] = None


class QARequest(BaseModel):
    """Request to test and compare Standard vs RAG question answering."""
    question: str
    top_k: int = Field(default=5, ge=1, le=50)
    retrieval_mode: str = Field(default="semantic", description="'semantic' or 'hybrid'")
    use_reranking: bool = False
    backend: Optional[str] = None
    model: Optional[str] = None
    run_standard: bool = True
    run_rag: bool = True
    document_id: Optional[str] = None


class QAResponse(BaseModel):
    """Comparison response returned from QA session."""
    session_id: str
    question: str
    standard_answer: Optional[AnswerResult] = None
    rag_answer: Optional[AnswerResult] = None
    created_at: datetime


class QASessionInfo(BaseModel):
    """Summary of a stored QA session."""
    id: str
    question: str
    standard_answer: Optional[str] = None
    rag_answer: Optional[str] = None
    standard_latency_ms: float
    rag_latency_ms: float
    top_k: int
    model_used: str
    embedding_model: str
    session_time: datetime
    documents_used: List[str] = Field(default_factory=list)

    model_config = ConfigDict(from_attributes=True)


class QASessionListResponse(BaseModel):
    """Paginated list of QA sessions."""
    total: int
    sessions: List[QASessionInfo]


# ---------------------------------------------------------
# Evaluation Schemas
# ---------------------------------------------------------

class MetricResult(BaseModel):
    """Single computed evaluation metric."""
    id: Optional[str] = None
    qa_session_id: Optional[str] = None
    metric_name: str
    metric_value: float
    is_reference_based: bool
    computed_at: Optional[datetime] = None
    notes: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class EvaluationRequest(BaseModel):
    """Payload for evaluating an answer against context and optional ground truth."""
    qa_session_id: Optional[str] = None
    question: str
    answer: str
    context_chunks: List[str] = Field(default_factory=list)
    reference_answer: Optional[str] = None
    retrieved_ids: Optional[List[str]] = None
    relevant_ids: Optional[List[str]] = None


class EvaluationResponse(BaseModel):
    """Metrics computed for the answer."""
    evaluation_id: Optional[str] = None
    qa_session_id: Optional[str] = None
    metrics: Dict[str, float]
    error_taxonomy: Optional[Dict[str, float]] = None
    details: Dict[str, Any] = Field(default_factory=dict)


class EvaluationListResponse(BaseModel):
    """List of evaluation results."""
    total: int
    results: List[MetricResult]


# ---------------------------------------------------------
# Experiment Schemas
# ---------------------------------------------------------

class ExperimentConfig(BaseModel):
    """Configuration definition for benchmarking."""
    variable: str = Field(..., description="Parameter to vary: 'retrieval_mode', 'reranking', 'top_k', 'llm_model', 'context_relevance', 'chunk_size', 'embedding_model'")
    values: List[Any] = Field(..., description="List of values to test for the variable")
    questions: List[str] = Field(default_factory=list, description="List of test questions (optional if benchmark_dataset is set)")
    reference_answers: Optional[List[Optional[str]]] = None
    benchmark_dataset: Optional[str] = Field(default=None, description="Standard benchmark dataset: 'ragtruth', 'halueval', or 'all'")
    num_runs: int = Field(default=1, ge=1, le=10, description="Number of runs per condition for statistical confidence intervals")
    default_top_k: int = 5
    default_retrieval_mode: str = "semantic"
    default_use_reranking: bool = False
    backend: Optional[str] = None
    model: Optional[str] = None


class ExperimentRunRequest(BaseModel):
    """Payload to trigger an experiment run."""
    name: str
    description: Optional[str] = None
    config: ExperimentConfig


class ExperimentResult(BaseModel):
    """Experiment benchmark record."""
    id: str
    name: str
    description: Optional[str] = None
    status: str
    config: Dict[str, Any]
    results: Optional[Dict[str, Any]] = None
    created_at: datetime
    completed_at: Optional[datetime] = None
    num_queries: int

    model_config = ConfigDict(from_attributes=True)


class ExperimentListResponse(BaseModel):
    """List of benchmark experiments."""
    total: int
    experiments: List[ExperimentResult]


# ---------------------------------------------------------
# Analytics & Reports Schemas
# ---------------------------------------------------------

class AnalyticsSummary(BaseModel):
    """Global system analytics summary."""
    total_documents: int
    total_chunks: int
    total_qa_sessions: int
    total_evaluations: int
    total_experiments: int
    avg_standard_latency_ms: float
    avg_rag_latency_ms: float
    avg_faithfulness: float
    avg_hallucination_rate: float
    avg_answer_relevance: float
    avg_answer_correctness: float


class ModelComparison(BaseModel):
    """Performance and hallucination comparison across different models/configurations."""
    models: List[Dict[str, Any]]


class TimeSeriesPoint(BaseModel):
    """Data point in time series analysis."""
    timestamp: str
    value: float


class MetricTimeSeriesResponse(BaseModel):
    """Metric values over time."""
    metric_name: str
    points: List[TimeSeriesPoint]


# ---------------------------------------------------------
# System Settings Schemas
# ---------------------------------------------------------

class SettingsRequest(BaseModel):
    """Mutable runtime settings request."""
    debug: Optional[bool] = None
    default_llm_backend: Optional[str] = None
    default_groq_model: Optional[str] = None
    embedding_model: Optional[str] = None
    reranker_model: Optional[str] = None
    default_top_k: Optional[int] = None
    default_chunk_size: Optional[int] = None
    default_chunk_overlap: Optional[int] = None
    groq_api_key: Optional[str] = None
    openai_api_key: Optional[str] = None
    ollama_base_url: Optional[str] = None


class SettingsResponse(BaseModel):
    """Current system settings."""
    app_name: str
    debug: bool
    default_llm_backend: str
    default_groq_model: str
    embedding_model: str
    reranker_model: str
    default_top_k: int
    default_chunk_size: int
    default_chunk_overlap: int
    max_file_size_mb: int
    groq_key_set: bool
    openai_key_set: bool
    ollama_base_url: str
    faiss_index_path: str
    database_url: str
