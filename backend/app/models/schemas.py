"""Pydantic v2 schemas for all API request and response data transfers."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, model_validator


# ---------------------------------------------------------
# Document & Chunk Schemas
# ---------------------------------------------------------

class DocumentInfo(BaseModel):
    """Document entity view."""
    id: str
    filename: str
    file_type: str
    file_size: int
    num_chunks: int
    upload_time: datetime
    description: Optional[str] = None
    metadata_json: Optional[str] = "{}"

    model_config = ConfigDict(from_attributes=True)


class DocumentUploadResponse(BaseModel):
    """Response returned upon successful document upload and chunk indexing."""
    id: str
    filename: str
    file_type: str
    file_size: int
    num_chunks: int
    upload_time: datetime
    message: str = "Document processed and indexed successfully"

    model_config = ConfigDict(from_attributes=True)


class DocumentListResponse(BaseModel):
    """List of uploaded documents."""
    total: int
    documents: List[DocumentInfo]


class ChunkInfo(BaseModel):
    """Information regarding a single indexed document chunk."""
    id: str
    document_id: str
    chunk_index: int
    content: str
    char_count: int
    token_estimate: int
    embedding_model: str

    model_config = ConfigDict(from_attributes=True)


class ChunkListResponse(BaseModel):
    """Paginated list of document chunks."""
    total: int
    chunks: List[ChunkInfo]


# ---------------------------------------------------------
# Retrieval Schemas
# ---------------------------------------------------------

class RetrievedChunk(BaseModel):
    """Details of a retrieved chunk matching a query."""
    chunk_id: str
    document_id: str
    filename: str
    chunk_index: int
    content: str
    score: float
    rank: int


class RetrievalQuery(BaseModel):
    """Payload to perform similarity or hybrid search."""
    query: str
    top_k: int = Field(default=5, ge=1, le=50)
    mode: str = Field(default="semantic", description="Retrieval mode: 'semantic' or 'hybrid'")
    use_reranking: bool = False
    document_id: Optional[str] = None


class RetrievalResult(BaseModel):
    """Result of vector retrieval."""
    query: str
    total_retrieved: int
    retrieval_mode: str
    reranked: bool
    latency_ms: float
    chunks: List[RetrievedChunk]


# ---------------------------------------------------------
# QA & LLM Inference Schemas
# ---------------------------------------------------------

class AnswerResult(BaseModel):
    """Answer generated by LLM along with runtime stats."""
    answer: str
    latency_ms: float
    model: str
    backend: str
    retrieved_chunks: Optional[List[RetrievedChunk]] = None


class QARequest(BaseModel):
    """Request to test and compare Standard vs RAG question answering."""
    question: str
    top_k: int = Field(default=5, ge=1, le=50)
    retrieval_mode: str = Field(default="semantic", description="'semantic' or 'hybrid'")
    use_reranking: bool = False
    backend: Optional[str] = None
    model: Optional[str] = None
    llm_backend: Optional[str] = None
    llm_model: Optional[str] = None
    reference_answer: Optional[str] = None
    run_standard: bool = True
    run_rag: bool = True
    document_id: Optional[str] = None

    @model_validator(mode="before")
    @classmethod
    def resolve_aliases(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "llm_backend" in data and not data.get("backend"):
                data["backend"] = data["llm_backend"]
            if "llm_model" in data and not data.get("model"):
                data["model"] = data["llm_model"]
        return data


class QAResponse(BaseModel):
    """Comparison response returned from QA session."""
    session_id: str
    question: str
    standard_answer: Optional[AnswerResult] = None
    rag_answer: Optional[AnswerResult] = None
    created_at: datetime


class QASessionInfo(BaseModel):
    """Summary of a stored QA session."""
    id: str
    question: str
    standard_answer: Optional[str] = None
    rag_answer: Optional[str] = None
    standard_latency_ms: float
    rag_latency_ms: float
    top_k: int
    model_used: str
    embedding_model: str
    session_time: datetime
    documents_used: List[str] = Field(default_factory=list)

    model_config = ConfigDict(from_attributes=True)


class QASessionListResponse(BaseModel):
    """Paginated list of QA sessions."""
    total: int
    sessions: List[QASessionInfo]


