# ---------------------------------------------------------
# Experiment Schemas
# ---------------------------------------------------------

class ExperimentConfig(BaseModel):
    """Configuration definition for benchmarking."""
    variable: str = Field(..., description="Parameter to vary: 'retrieval_mode', 'reranking', 'top_k', 'llm_model', 'context_relevance', 'chunk_size', 'embedding_model'")
    values: List[Any] = Field(..., description="List of values to test for the variable")
    questions: List[str] = Field(default_factory=list, description="List of test questions (optional if benchmark_dataset is set)")
    reference_answers: Optional[List[Optional[str]]] = None
    benchmark_dataset: Optional[str] = Field(default=None, description="Standard benchmark dataset: 'ragtruth', 'halueval', or 'all'")
    num_runs: int = Field(default=1, ge=1, le=10, description="Number of runs per condition for statistical confidence intervals")
    default_top_k: int = 5
    default_retrieval_mode: str = "semantic"
    default_use_reranking: bool = False
    backend: Optional[str] = None
    model: Optional[str] = None


class ExperimentRunRequest(BaseModel):
    """Payload to trigger an experiment run."""
    name: str
    description: Optional[str] = None
    config: Optional[ExperimentConfig] = None

    @model_validator(mode="before")
    @classmethod
    def wrap_flat_config(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if data.get("config") is None:
                cfg_keys = {
                    "variable", "values", "questions", "reference_answers",
                    "benchmark_dataset", "num_runs", "default_top_k",
                    "default_retrieval_mode", "default_use_reranking",
                    "backend", "model",
                }
                extracted = {k: v for k, v in data.items() if k in cfg_keys}
                if "base_config" in data and isinstance(data["base_config"], dict):
                    bc = data["base_config"]
                    if "top_k" in bc and "default_top_k" not in extracted:
                        extracted["default_top_k"] = bc["top_k"]
                    if "retrieval_mode" in bc and "default_retrieval_mode" not in extracted:
                        extracted["default_retrieval_mode"] = bc["retrieval_mode"]
                    if "use_reranking" in bc and "default_use_reranking" not in extracted:
                        extracted["default_use_reranking"] = bc["use_reranking"]
                    if "llm_backend" in bc and "backend" not in extracted:
                        extracted["backend"] = bc["llm_backend"]
                    if "llm_model" in bc and "model" not in extracted:
                        extracted["model"] = bc["llm_model"]
                data["config"] = extracted
        return data


class ExperimentResult(BaseModel):
    """Experiment benchmark record."""
    id: str
    name: str
    description: Optional[str] = None
    status: str
    config: Dict[str, Any]
    results: Optional[Dict[str, Any]] = None
    runs: Optional[List[Dict[str, Any]]] = None
    created_at: datetime
    completed_at: Optional[datetime] = None
    num_queries: int

    model_config = ConfigDict(from_attributes=True)


class ExperimentListResponse(BaseModel):
    """List of benchmark experiments."""
    total: int
    experiments: List[ExperimentResult]


